close(capacity(40,6).grid,750);assert.ok(Math.abs(control(2).position-1)<.01);
assert.deepEqual(learnGrid().route,[0,1,2,3,4]);
assert.equal(validateAction({revision:2,asset:'teaching_camera',x:0}).ok,false);
assert.equal(validateAction({revision:3,asset:'teaching_camera',x:Infinity}).ok,false);
assert.equal(validateAction({revision:3,asset:'teaching_camera',x:.5}).ok,true);
const c=detection();assert.equal(c.tp+c.fn,100);assert.equal(c.tp+c.fp+c.tn+c.fn,1000);
assert.equal(reduceEvents([{time_s:1,type:'order_arrived'},{time_s:2,type:'shipped'}],1.5).shipped,0);
const fixture=JSON.parse(await readFile(new URL('../assets/policy-replay.json',import.meta.url),'utf8'));
